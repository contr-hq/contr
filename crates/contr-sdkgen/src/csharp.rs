//! C# SDK target: the `sdk/csharp` template, the proto files Grpc.Tools compiles at build time, and the product
//! identifiers and revision from this repository.

use std::fmt::Write;
use std::fs;
use std::io;
use std::path::Path;

use contr_core::product;

use crate::{Contract, Error};

/// Directory of the SDK project inside the template and the output.
pub const SDK_PROJECT: &str = "Contr.Sdk";

/// Directory of the conformance program inside the template and the output.
pub const VERIFY_PROJECT: &str = "Contr.Sdk.Verify";

const PROTOS_DIR: &str = "Protos";
const GENERATED_DIR: &str = "Generated";
const SKIPPED_DIRS: [&str; 4] = ["bin", "obj", PROTOS_DIR, GENERATED_DIR];

/// Writes a buildable C# solution tree for `contract` into `out_dir`, versioned `version`.
pub fn generate(contract: &Contract, template: &Path, out_dir: &Path, version: &str) -> Result<(), Error> {
    let write_error = |source| Error::Write {
        path: out_dir.to_path_buf(),
        source,
    };

    copy_template(template, out_dir).map_err(write_error)?;

    let project = out_dir.join(SDK_PROJECT);
    let protos = project.join(PROTOS_DIR);
    if protos.exists() {
        fs::remove_dir_all(&protos).map_err(write_error)?;
    }
    for file in contract.files() {
        let target = protos.join(file);
        if let Some(parent) = target.parent() {
            fs::create_dir_all(parent).map_err(write_error)?;
        }
        fs::copy(contract.root().join(file), &target).map_err(write_error)?;
    }

    let generated = project.join(GENERATED_DIR);
    fs::create_dir_all(&generated).map_err(write_error)?;
    fs::write(generated.join("Version.props"), version_props(version)).map_err(write_error)?;
    fs::write(
        generated.join("Product.g.cs"),
        product_source(contract.revision(), version),
    )
    .map_err(write_error)
}

fn copy_template(from: &Path, to: &Path) -> io::Result<()> {
    fs::create_dir_all(to)?;
    for entry in fs::read_dir(from)? {
        let entry = entry?;
        let target = to.join(entry.file_name());
        if entry.file_type()?.is_dir() {
            let skipped = entry
                .file_name()
                .to_str()
                .is_some_and(|name| SKIPPED_DIRS.contains(&name));
            if !skipped {
                copy_template(&entry.path(), &target)?;
            }
        } else {
            fs::copy(entry.path(), target)?;
        }
    }

    Ok(())
}

fn version_props(version: &str) -> String {
    format!(
        "<Project>\n  <PropertyGroup>\n    <Version>{}</Version>\n  </PropertyGroup>\n</Project>\n",
        xml_text(version)
    )
}

fn product_source(revision: u32, version: &str) -> String {
    let constants = [
        ("DisplayName", product::DISPLAY_NAME),
        ("Slug", product::SLUG),
        ("HostEnv", product::HOST_ENV),
        ("ApiSocketFile", product::API_SOCKET_FILE),
        ("DiscoveryFile", product::DISCOVERY_FILE),
        ("DaemonBinary", product::DAEMON_BINARY),
        ("SdkVersion", version),
    ];
    let strings = constants.iter().fold(String::new(), |mut source, (name, value)| {
        let _ = writeln!(source, "    public const string {name} = {};", csharp_string(value));
        source
    });

    format!(
        "// <auto-generated>contr-sdkgen</auto-generated>\n\
         namespace Contr.Sdk;\n\n\
         internal static class Product\n{{\n{strings}    public const uint ApiRevision = {revision};\n}}\n"
    )
}

fn csharp_string(value: &str) -> String {
    format!("\"{}\"", value.replace('\\', "\\\\").replace('"', "\\\""))
}

fn xml_text(value: &str) -> String {
    value.replace('&', "&amp;").replace('<', "&lt;").replace('>', "&gt;")
}

#[cfg(test)]
mod tests {
    use super::*;

    #[test]
    fn product_constants_come_from_contr_core() {
        let source = product_source(7, "1.2.3");

        assert!(source.contains(&format!("HostEnv = \"{}\";", product::HOST_ENV)));
        assert!(source.contains("SdkVersion = \"1.2.3\";"));
        assert!(source.contains("ApiRevision = 7;"));
    }

    #[test]
    fn copies_the_template_without_build_output() {
        let template = tempfile::tempdir().unwrap();
        let out = tempfile::tempdir().unwrap();
        fs::create_dir_all(template.path().join("Contr.Sdk/obj")).unwrap();
        fs::write(template.path().join("Contr.Sdk/obj/stale.json"), "{}").unwrap();
        fs::write(template.path().join("Contr.Sdk/Client.cs"), "class C {}").unwrap();

        copy_template(template.path(), out.path()).unwrap();

        assert!(out.path().join("Contr.Sdk/Client.cs").exists());
        assert!(!out.path().join("Contr.Sdk/obj").exists());
    }
}
